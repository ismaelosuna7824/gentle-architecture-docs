#!/usr/bin/env node
// Checks a repository's docs/ against its code: documents whose `sources`
// changed since the commit they were `verified` at, missing front matter,
// broken relative links and malformed Mermaid blocks. No dependencies.
//
// Usage (from the repository root):
//   node <skill>/scripts/docs-check.mjs [--docs docs] [--base <ref>] [--json] [--strict]
//
//   --base <ref>  also count changes on this branch since <ref> (e.g. main)
//   --json        machine-readable output
//   --strict      exit 1 when anything is found (for CI)

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name, fallback) => {
	const at = args.indexOf(name);
	return at >= 0 && args[at + 1] ? args[at + 1] : fallback;
};

const root = process.cwd();
const docsDir = resolve(root, option("--docs", "docs"));
const base = option("--base", null);
const DIAGRAMS = ["flowchart", "sequenceDiagram", "stateDiagram-v2", "erDiagram", "classDiagram"];
const ALSO_FINE = ["graph", "stateDiagram"];
const GENERATED = /generated by .*do not edit/i;

function git(...argv) {
	try {
		return execFileSync("git", argv, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
	} catch {
		return null;
	}
}

function markdownFiles(dir) {
	if (!existsSync(dir)) return [];
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) return markdownFiles(path);
		return name.endsWith(".md") ? [path] : [];
	});
}

/** The subset of YAML front matter the documents use: scalars and string lists. */
function frontMatter(text) {
	const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
	if (!match) return null;
	const out = {};
	let list = null;
	for (const line of match[1].split(/\r?\n/)) {
		const item = line.match(/^\s+-\s+(.*)$/);
		if (item && list) {
			out[list].push(item[1].replace(/^["']|["']$/g, "").trim());
			continue;
		}
		const pair = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
		if (!pair) continue;
		const value = pair[2].replace(/\s+#.*$/, "").trim();
		if (value === "") {
			list = pair[1];
			out[list] = [];
		} else {
			list = null;
			out[pair[1]] = value.replace(/^["']|["']$/g, "");
		}
	}
	return out;
}

/** `src/**`, `*.ts`, `a/?b` as a regular expression over repository paths. */
function globToRegex(glob) {
	let out = "";
	for (let i = 0; i < glob.length; i++) {
		const c = glob[i];
		if (c === "*" && glob[i + 1] === "*") {
			out += ".*";
			i++;
			if (glob[i + 1] === "/") i++;
		} else if (c === "*") out += "[^/]*";
		else if (c === "?") out += "[^/]";
		else out += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
	}
	return new RegExp(`^${out}$`);
}

function changedSince(commit) {
	const committed = git("diff", "--name-only", `${commit}..HEAD`);
	if (committed === null) return null;
	return committed.split("\n").filter(Boolean);
}

const uncommitted = (git("status", "--porcelain") ?? "")
	.split("\n")
	.filter(Boolean)
	.map((line) => line.slice(3).split(" -> ").pop());
const onBranch = base ? (git("diff", "--name-only", `${base}...HEAD`) ?? "").split("\n").filter(Boolean) : [];
const head = git("rev-parse", "--short", "HEAD");

const findings = [];
const add = (file, kind, message, extra = {}) =>
	findings.push({ file: relative(root, file).split(sep).join("/"), kind, message, ...extra });

const files = markdownFiles(docsDir);
if (files.length === 0) add(docsDir, "missing", "No Markdown documents found; run `init`.");

for (const file of files) {
	const text = readFileSync(file, "utf8");
	const isIndex = file === join(docsDir, "README.md");
	const generated = GENERATED.test(text.slice(0, 400));

	// Front matter and staleness.
	const meta = frontMatter(text);
	if (!meta && !isIndex && !generated) {
		add(file, "front-matter", "No front matter (title, owner, sources, verified, status).");
	} else if (meta) {
		for (const key of ["title", "owner", "sources", "verified", "status"]) {
			if (!(key in meta)) add(file, "front-matter", `Front matter has no \`${key}\`.`);
		}
		const sources = Array.isArray(meta.sources) ? meta.sources.filter((s) => s !== "TBD") : [];
		const patterns = sources.map(globToRegex);
		const matching = (paths) => [...new Set(paths)].filter((p) => patterns.some((re) => re.test(p)));
		if (meta.status === "stale") add(file, "stale", "Marked stale.");
		if (!meta.verified || meta.verified === "TBD") {
			if (meta.status !== "draft") add(file, "unverified", "Never verified against its sources.");
		} else if (sources.length) {
			const since = changedSince(meta.verified);
			if (since === null) {
				add(file, "unverified", `\`verified: ${meta.verified}\` is not a commit in this repository.`);
			} else {
				const changed = matching([...since, ...onBranch, ...uncommitted]);
				if (changed.length) {
					add(file, "stale", `${changed.length} source file(s) changed since ${meta.verified}.`, { changed });
				}
			}
		}
		for (const source of sources) {
			const literal = !/[*?]/.test(source);
			if (literal && !existsSync(join(root, source))) add(file, "source", `Source \`${source}\` does not exist.`);
		}
	}

	// Relative links.
	const withoutCode = text.replace(/```[\s\S]*?```/g, "");
	for (const [, target] of withoutCode.matchAll(/\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
		if (/^(https?:|mailto:|#|data:)/.test(target)) continue;
		const path = decodeURI(target.split("#")[0]);
		if (path && !existsSync(resolve(dirname(file), path))) add(file, "link", `Broken link: ${target}`);
	}

	// Mermaid blocks.
	const fences = [...text.matchAll(/^```(\S*)\s*$/gm)];
	if (fences.length % 2 !== 0) add(file, "mermaid", "A fenced block is not closed.");
	for (const [, body] of text.matchAll(/^```mermaid\s*\n([\s\S]*?)^```\s*$/gm)) {
		const first = body.split("\n").map((l) => l.trim()).find((l) => l && !l.startsWith("%%"));
		const type = first?.split(/\s/)[0];
		if (!type) add(file, "mermaid", "Empty Mermaid block.");
		else if (!DIAGRAMS.includes(type) && !ALSO_FINE.includes(type)) {
			add(file, "mermaid", `Diagram type \`${type}\` may not render everywhere; use ${DIAGRAMS.join(", ")}.`);
		}
	}
}

if (flag("--json")) {
	console.log(JSON.stringify({ head, documents: files.length, findings }, null, 2));
} else if (findings.length === 0) {
	console.log(`docs-check: ${files.length} document(s), all current at ${head}.`);
} else {
	const byFile = new Map();
	for (const f of findings) byFile.set(f.file, [...(byFile.get(f.file) ?? []), f]);
	console.log(`docs-check: ${findings.length} finding(s) in ${byFile.size} of ${files.length} document(s) (HEAD ${head})\n`);
	for (const [file, list] of byFile) {
		console.log(file);
		for (const f of list) {
			console.log(`  - [${f.kind}] ${f.message}`);
			for (const c of f.changed ?? []) console.log(`      ${c}`);
		}
	}
}
process.exit(flag("--strict") && findings.length ? 1 : 0);
